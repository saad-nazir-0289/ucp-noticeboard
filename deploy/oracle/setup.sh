#!/usr/bin/env bash
# One-time setup of the Oracle server for NoticeBoard (Ubuntu 22.04 or 24.04).
# On the server, as the default "ubuntu" user:
#
#   curl -fsSL https://raw.githubusercontent.com/saad-nazir-0289/ucp-noticeboard/staging/deploy/oracle/setup.sh -o setup.sh
#   sudo bash setup.sh --api-domain ucpnb-api.duckdns.org --staging-domain ucpnb-staging.duckdns.org
#
# Safe to run again: it skips whatever is already done and never overwrites
# your settings. See docs/ORACLE.md for the whole walkthrough.
set -euo pipefail

API_DOMAIN="" STAGING_API_DOMAIN="" BRANCH=staging DUCKDNS_TOKEN="" SKIP_SYSTEM=0
REPO_URL=https://github.com/saad-nazir-0289/ucp-noticeboard.git
OWNER=${SUDO_USER:-ubuntu}
while [ $# -gt 0 ]; do
  case "$1" in
    --api-domain) API_DOMAIN=$2; shift 2 ;;
    --staging-domain) STAGING_API_DOMAIN=$2; shift 2 ;;
    --branch) BRANCH=$2; shift 2 ;;
    --duckdns-token) DUCKDNS_TOKEN=$2; shift 2 ;;
    --skip-system) SKIP_SYSTEM=1; shift ;;   # for testing the rest elsewhere
    --repo-url) REPO_URL=$2; shift 2 ;;      # likewise
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
done

main() {
  [ "$(id -u)" = 0 ] || { echo "Run with sudo." >&2; exit 1; }
  [ -n "$API_DOMAIN" ] && [ -n "$STAGING_API_DOMAIN" ] || { echo "Give --api-domain and --staging-domain." >&2; exit 1; }
  local root=/opt/ucpnb home; home=$(getent passwd "$OWNER" | cut -d: -f6)

  if [ "$SKIP_SYSTEM" = 0 ]; then
    step "System packages and automatic security updates"
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq
    apt-get install -y -qq git curl ca-certificates openssl openssh-client unattended-upgrades iptables-persistent >/dev/null
    dpkg-reconfigure -f noninteractive unattended-upgrades >/dev/null

    step "Firewall: allow web traffic (ports 80 and 443)"
    # Oracle's Ubuntu images refuse everything except SSH at the server
    # itself, on top of the cloud's own rules (open those too: see the guide).
    # Saved before Docker is installed, so Docker's own rules aren't frozen in.
    for port in 80 443; do
      iptables -C INPUT -p tcp --dport "$port" -m state --state NEW -j ACCEPT 2>/dev/null \
        || iptables -I INPUT 5 -p tcp --dport "$port" -m state --state NEW -j ACCEPT 2>/dev/null \
        || iptables -I INPUT 1 -p tcp --dport "$port" -m state --state NEW -j ACCEPT
    done
    netfilter-persistent save >/dev/null

    step "Docker"
    if ! command -v docker >/dev/null; then curl -fsSL https://get.docker.com | sh >/dev/null; fi
    usermod -aG docker "$OWNER"
    systemctl enable --now docker >/dev/null

    step "Swap (helps the 1 GB servers)"
    if [ "$(free -m | awk '/Mem:/ {print $2}')" -lt 3000 ] && ! swapon --show | grep -q /swapfile; then
      fallocate -l 3G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
      grep -q /swapfile /etc/fstab || echo "/swapfile none swap sw 0 0" >> /etc/fstab
    fi

    if [ -n "$DUCKDNS_TOKEN" ]; then
      step "Keep the DuckDNS names pointing at this server"
      local names; names=$(echo "$API_DOMAIN,$STAGING_API_DOMAIN" | sed 's/\.duckdns\.org//g')
      echo "*/10 * * * * $OWNER curl -fsS 'https://www.duckdns.org/update?domains=$names&token=$DUCKDNS_TOKEN' >/dev/null 2>&1" > /etc/cron.d/ucpnb-duckdns
      chmod 600 /etc/cron.d/ucpnb-duckdns
    fi
  fi

  step "The code"
  mkdir -p "$root"/{config,backups,src}
  [ -d "$root/repo/.git" ] || git clone --quiet --branch "$BRANCH" "$REPO_URL" "$root/repo"
  chown -R "$OWNER": "$root"
  # So git still works if a script is ever started with sudo.
  for dir in "$root/repo" "$root/src/production" "$root/src/staging"; do
    git config --system --get-all safe.directory | grep -qx "$dir" || git config --system --add safe.directory "$dir"
  done
  chmod 700 "$root/config" "$root/backups"

  step "Settings (kept if they already exist)"
  local stack=$root/config/stack.env
  if [ ! -f "$stack" ]; then
    cat > "$stack" <<CONF
# Shared by the whole server. Generated by setup.sh.
POSTGRES_PASSWORD=$(openssl rand -hex 24)
API_DOMAIN=$API_DOMAIN
STAGING_API_DOMAIN=$STAGING_API_DOMAIN
CONF
  fi
  if [ ! -f "$root/config/staging.env" ]; then
    sed -e "s#^Jwt__Key=GENERATED#Jwt__Key=$(openssl rand -base64 48 | tr -d '\n')#" \
        -e "s#^AdminActivationSecret=GENERATED#AdminActivationSecret=$(openssl rand -hex 24)#" \
        "$root/repo/deploy/oracle/env/staging.env.example" > "$root/config/staging.env"
  fi
  cp "$root/repo/deploy/oracle/env/production.env.example" "$root/config/production.env.example"
  chown -R "$OWNER": "$root/config"
  chmod 600 "$root"/config/*

  step "Nightly backup of the production database (kept 14 days)"
  echo "17 21 * * * $OWNER [ -f $root/config/production.env ] && $root/repo/deploy/oracle/backup.sh production >> $root/backups/backup.log 2>&1" > /etc/cron.d/ucpnb-backup
  chmod 644 /etc/cron.d/ucpnb-backup

  step "A key for GitHub to deploy with (it can only deploy and back up)"
  local key=$home/.ssh/github_actions
  mkdir -p "$home/.ssh"
  if [ ! -f "$key" ]; then
    ssh-keygen -q -t ed25519 -N "" -C "github-actions-deploy" -f "$key"
    echo "command=\"$root/repo/deploy/oracle/gate.sh\",no-port-forwarding,no-agent-forwarding,no-X11-forwarding,no-pty $(cat "$key.pub")" >> "$home/.ssh/authorized_keys"
  fi
  chown -R "$OWNER": "$home/.ssh"
  chmod 700 "$home/.ssh"; chmod 600 "$home/.ssh/authorized_keys" "$key"

  step "Done"
  cat <<NEXT

Next (docs/ORACLE.md, "Finish the setup"):
  0. Log out and back in (so your user can use Docker), then:
  1. Edit the staging settings:   nano $root/config/staging.env
     (put in your staging site's address where it says STAGING_PWA_URL)
  2. Start staging:               $root/repo/deploy/oracle/deploy.sh staging
  3. Check:                       https://$STAGING_API_DOMAIN/health
  4. For GitHub deploys, add this private key as the ORACLE_SSH_KEY secret
     (print it with: cat $key)
NEXT
}

step() { printf '\n== %s\n' "$*"; }

main
